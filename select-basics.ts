//SELECT is used to select a specific value from a list of values. It is often used in conjunction with the FROM clause to specify the source of the data.

//GROUP BY: The GROUP BY clause is used to group rows that have the same values in specified columns into summary rows.

//2. JOIN: The JOIN clause is used to combine rows from two or more tables based on a related column between them. There are different types of joins, including INNER JOIN, LEFT JOIN, RIGHT JOIN, and FULL OUTER JOIN.

//3. WHERE: The WHERE clause is used to filter records based on specified conditions. It allows you to retrieve only the rows that meet certain criteria.

//4. ORDER BY: The ORDER BY clause is used to sort the result set of a query by one or more columns. You can specify ascending (ASC) or descending (DESC) order.

//5. LIMIT: The LIMIT clause is used to specify the maximum number of records to return in the result set. It is often used for pagination or to restrict the number of rows returned by a query.

//6. DISTINCT: The DISTINCT keyword is used to return only unique (distinct) values in the result set, eliminating duplicate rows.

//7. HAVING: The HAVING clause is used to filter groups of rows created by the GROUP BY clause based on specified conditions. It is similar to the WHERE clause but operates on aggregated data.

//8. UNION: The UNION operator is used to combine the result sets of two or more SELECT statements into a single result set. It removes duplicate rows by default, but you can use UNION ALL to include duplicates.

//9. SUBQUERY: A subquery is a query nested inside another query. It can be used in various clauses, such as SELECT, FROM, WHERE, and HAVING, to provide intermediate results for the main query.

//10. ALIAS: An alias is a temporary name given to a table or column in a query. It is often used to make the output more readable or to simplify complex queries. You can create an alias using the AS keyword.

